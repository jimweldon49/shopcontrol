// ---------------------------------------------------------------- HTML
const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const inline = (s) => esc(s).replace(/\*\*(.+?)\*\*/g, "<b>$1</b>");

function blockHtml(b) {
  if (b.p) return `<p>${inline(b.p)}</p>`;
  if (b.h3) return `<h3>${inline(b.h3)}</h3>`;
  if (b.steps) return `<ol class="steps">${b.steps.map((s) => `<li>${inline(s)}</li>`).join("")}</ol>`;
  if (b.bullets) return `<ul>${b.bullets.map((s) => `<li>${inline(s)}</li>`).join("")}</ul>`;
  if (b.tip) return `<div class="callout tip"><b>Tip</b><span>${inline(b.tip)}</span></div>`;
  if (b.note) return `<div class="callout note"><b>Note</b><span>${inline(b.note)}</span></div>`;
  if (b.table) return `<div class="table-wrap"><table><thead><tr>${b.table.head.map((h) => `<th>${inline(h)}</th>`).join("")}</tr></thead><tbody>${b.table.rows.map((r) => `<tr>${r.map((c) => `<td>${inline(c)}</td>`).join("")}</tr>`).join("")}</tbody></table></div>`;
  throw Error("Unknown block: " + JSON.stringify(b));
}

