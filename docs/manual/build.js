// ---------------------------------------------------------------- Word
async function buildDocx() {
  const d = require("docx");
  const { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, ImageRun, Table, TableRow, TableCell, WidthType, ShadingType,
    BorderStyle, LevelFormat, PageBreak, TableOfContents, Footer, Header, PageNumber } = d;
  const FONT = "Calibri";
  const ORANGE = "E8620E", DARK = "1F2933", MUTED = "5B6776";

  const runs = (text, base = {}) => String(text).split(/(\*\*.+?\*\*)/).filter(Boolean).map((part) =>
    part.startsWith("**") ? new TextRun({ ...base, text: part.slice(2, -2), bold: true }) : new TextRun({ ...base, text: part }));

  let stepsInstance = 0;
  const children = [];
  const CONTENT_WIDTH = 9360; // 6.5" at 1" margins on US Letter

  function block(b) {
    if (b.p) return [new Paragraph({ children: runs(b.p), spacing: { after: 120 } })];
    if (b.h3) return [new Paragraph({ heading: HeadingLevel.HEADING_2, children: runs(b.h3) })];
    if (b.bullets) return b.bullets.map((s) => new Paragraph({ children: runs(s), numbering: { reference: "bullets", level: 0 }, spacing: { after: 60 } }));
    if (b.steps) { stepsInstance++; return b.steps.map((s) => new Paragraph({ children: runs(s), numbering: { reference: "steps", level: 0, instance: stepsInstance }, spacing: { after: 60 } })); }
    if (b.tip || b.note) {
      const color = b.tip ? "2F9E5B" : "C99A06", fill = b.tip ? "EAF7EF" : "FFF8DD";
      return [new Paragraph({
        children: [new TextRun({ text: b.tip ? "Tip:  " : "Note:  ", bold: true, color }), ...runs(b.tip || b.note)],
        shading: { type: ShadingType.CLEAR, fill, color: "auto" },
        border: { left: { style: BorderStyle.SINGLE, size: 24, color, space: 8 } },
        spacing: { before: 120, after: 160 }, indent: { left: 160, right: 160 },
      })];
    }
    if (b.table) {
      const cols = b.table.head.length;
      const widths = cols === 2 ? [2900, CONTENT_WIDTH - 2900] : Array(cols).fill(Math.floor(CONTENT_WIDTH / cols));
      const border = { style: BorderStyle.SINGLE, size: 4, color: "C9CFD6" };
      const borders = { top: border, bottom: border, left: border, right: border };
      const cell = (text, i, head) => new TableCell({
        width: { size: widths[i], type: WidthType.DXA }, borders,
        shading: head ? { type: ShadingType.CLEAR, fill: "1F2933", color: "auto" } : undefined,
        margins: { top: 80, bottom: 80, left: 120, right: 120 },
        children: [new Paragraph({ children: runs(text, head ? { bold: true, color: "FFFFFF" } : (i === 0 ? { bold: true } : {})) })],
      });
      return [new Table({
        width: { size: CONTENT_WIDTH, type: WidthType.DXA }, columnWidths: widths,
        rows: [new TableRow({ tableHeader: true, children: b.table.head.map((h, i) => cell(h, i, true)) }),
          ...b.table.rows.map((r) => new TableRow({ cantSplit: true, children: r.map((c, i) => cell(c, i, false)) }))],
      }), new Paragraph({ children: [], spacing: { after: 80 } })];
    }
    throw Error("Unknown block");
  }

  // Cover
  children.push(
    new Paragraph({ children: [], spacing: { before: 2200 } }),
    new Paragraph({ alignment: AlignmentType.CENTER, children: [new ImageRun({ type: "png", data: fs.readFileSync(LOGO), transformation: { width: 420, height: 156 } })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 480, after: 120 }, children: [new TextRun({ text: "ShopControl User Manual", bold: true, size: 56, color: DARK })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: "Concept Autobody staff guide", size: 28, color: MUTED })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 240 }, children: [new TextRun({ text: `Version ${VERSION}  ·  Updated ${UPDATED}`, size: 22, color: MUTED })] }),
    new Paragraph({ children: [new PageBreak()] }),
    new Paragraph({ spacing: { after: 200 }, border: { bottom: { style: BorderStyle.SINGLE, size: 12, color: ORANGE, space: 6 } }, children: [new TextRun({ text: "Contents", bold: true, size: 36, color: DARK })] }),
    new TableOfContents("Contents", { hyperlink: true, headingStyleRange: "1-2" }),
    new Paragraph({ children: [new PageBreak()] }),
  );

  sections.forEach((s, i) => {
    children.push(new Paragraph({ heading: HeadingLevel.HEADING_1, pageBreakBefore: i > 0, children: [new TextRun(`${i + 1}.  ${s.title}`)] }));
    s.blocks.forEach((b) => children.push(...block(b)));
  });

  children.push(new Paragraph({ heading: HeadingLevel.HEADING_1, pageBreakBefore: true, children: [new TextRun("Manual versions")] }));
  children.push(...block({ table: { head: ["Version", "Date", "What changed"], rows: CHANGES.map((c) => [c.version, c.date, c.text]) } }));

  const doc = new Document({
    creator: "Concept Autobody", title: "ShopControl User Manual", description: `Version ${VERSION}`,
    features: { updateFields: true },
    styles: {
      default: { document: { run: { font: FONT, size: 22, color: "222222" }, paragraph: { spacing: { line: 276 } } } },
      paragraphStyles: [
        { id: "Heading1", name: "Heading 1", basedOn: "Normal", next: "Normal", quickFormat: true,
          run: { size: 36, bold: true, color: DARK, font: FONT },
          paragraph: { spacing: { before: 120, after: 200 }, outlineLevel: 0, border: { bottom: { style: BorderStyle.SINGLE, size: 12, color: ORANGE, space: 6 } } } },
        { id: "Heading2", name: "Heading 2", basedOn: "Normal", next: "Normal", quickFormat: true,
          run: { size: 26, bold: true, color: ORANGE, font: FONT },
          paragraph: { spacing: { before: 280, after: 100 }, outlineLevel: 1, keepNext: true } },
      ],
    },
    numbering: { config: [
      { reference: "bullets", levels: [{ level: 0, format: LevelFormat.BULLET, text: "•", alignment: AlignmentType.LEFT, style: { paragraph: { indent: { left: 540, hanging: 270 } } } }] },
      { reference: "steps", levels: [{ level: 0, format: LevelFormat.DECIMAL, text: "%1.", alignment: AlignmentType.LEFT, style: { run: { bold: true, color: ORANGE }, paragraph: { indent: { left: 540, hanging: 360 } } } }] },
    ] },
    sections: [{
      properties: { page: { size: { width: 12240, height: 15840 }, margin: { top: 1440, bottom: 1440, left: 1440, right: 1440 } }, titlePage: true },
      headers: { default: new Header({ children: [new Paragraph({ alignment: AlignmentType.RIGHT, children: [new TextRun({ text: "ShopControl User Manual", size: 18, color: MUTED })] })] }) },
      footers: { default: new Footer({ children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: `Concept Autobody  ·  Version ${VERSION}  ·  Page `, size: 18, color: MUTED }), new TextRun({ children: [PageNumber.CURRENT], size: 18, color: MUTED })] })] }) },
      children,
    }],
  });
  return Packer.toBuffer(doc);
}

(async () => {
  const htmlPath = path.join(ROOT, "client", "manual", "index.html");
  fs.mkdirSync(path.dirname(htmlPath), { recursive: true });
  fs.writeFileSync(htmlPath, buildHtml());
  console.log("Wrote", path.relative(ROOT, htmlPath));
  const docxPath = path.join(ROOT, "client", "manual", "ShopControl-User-Manual.docx");
  fs.writeFileSync(docxPath, await buildDocx());
  console.log("Wrote", path.relative(ROOT, docxPath));
})().catch((e) => { console.error(e); process.exit(1); });
